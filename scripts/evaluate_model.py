"""Compare model variants with repeated, nested cross-validation.

For every outer fold the decision threshold is chosen on out-of-fold predictions
of the outer training part only, then applied to the outer test part. The
reported cost is therefore an honest estimate, not an in-sample optimum.

Usage:  python scripts/evaluate_model.py   (writes reports/model_comparison.md)
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from credit_risk.data import load_german_credit  # noqa: E402
from credit_risk.model import ModelConfig, build_pipeline, decision_metrics, optimal_threshold  # noqa: E402

REPEATS = 3
FOLDS = 5


def logistic_regression(config: ModelConfig) -> Pipeline:
    numeric, ordinal, nominal = config.features()
    pre = ColumnTransformer([
        ("num", StandardScaler(), numeric),
        ("cat", OneHotEncoder(handle_unknown="ignore", sparse_output=False), list(ordinal) + nominal),
    ])
    return Pipeline([("preprocessor", pre), ("model", LogisticRegression(C=0.5, max_iter=2000))])


VARIANTS = {
    "Logistic regression (baseline)": lambda: logistic_regression(ModelConfig()),
    "XGBoost, no monotone constraints": lambda: build_pipeline(ModelConfig(monotone=False)),
    "XGBoost, incl. protected attributes": lambda: build_pipeline(ModelConfig(exclude_protected=False)),
    "XGBoost, monotone, protected excluded (dashboard default)": lambda: build_pipeline(ModelConfig()),
}


def evaluate(make_model, X, y) -> dict:
    aucs, costs, approvals, bad_rates = [], [], [], []
    for rep in range(REPEATS):
        outer = StratifiedKFold(FOLDS, shuffle=True, random_state=rep)
        for train_idx, test_idx in outer.split(X, y):
            X_tr, y_tr, X_te, y_te = X.iloc[train_idx], y.iloc[train_idx], X.iloc[test_idx], y.iloc[test_idx]
            inner = StratifiedKFold(FOLDS, shuffle=True, random_state=100 + rep)
            oof = cross_val_predict(make_model(), X_tr, y_tr, cv=inner, method="predict_proba")[:, 1]
            threshold = optimal_threshold(y_tr, oof)
            proba = make_model().fit(X_tr, y_tr).predict_proba(X_te)[:, 1]
            m = decision_metrics(y_te, proba, threshold)
            aucs.append(roc_auc_score(y_te, proba))
            costs.append(m["cost_per_application"])
            approvals.append(m["approval_rate"])
            bad_rates.append(m["bad_rate_among_approved"])
    return {
        "ROC-AUC": f"{np.mean(aucs):.3f} ± {np.std(aucs):.3f}",
        "Cost per application": f"{np.mean(costs):.3f}",
        "Approval rate": f"{np.mean(approvals):.1%}",
        "Bad rate among approved": f"{np.nanmean(bad_rates):.1%}",
    }


def main() -> None:
    X, y = load_german_credit()
    rows = {name: evaluate(make, X, y) for name, make in VARIANTS.items()}
    rows["Approve everyone (no model)"] = {
        "ROC-AUC": "–", "Cost per application": f"{(1 - y.mean()) * 5:.3f}",
        "Approval rate": "100.0%", "Bad rate among approved": f"{1 - y.mean():.1%}",
    }
    table = pd.DataFrame(rows).T
    text = (
        "# Model comparison\n\n"
        f"Nested, stratified {FOLDS}-fold cross-validation, repeated {REPEATS} times (1,000 applicants). "
        "Cost = 5 × approved bad + 1 × rejected good, per application; the threshold is tuned "
        "inside each training fold. Generated by `scripts/evaluate_model.py`.\n\n"
        + table.to_markdown() + "\n"
    )
    out = ROOT / "reports" / "model_comparison.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
